/// <reference types="vitest/config" />
import { fileURLToPath, URL } from 'node:url';
import { defineConfig } from 'vite';
import react from '@vitejs/plugin-react';
import tailwindcss from '@tailwindcss/vite';
import { VitePWA } from 'vite-plugin-pwa';
import { brand } from './src/app/brand';

export default defineConfig({
  plugins: [
    // %BRAND_NAME% et %BRAND_DESCRIPTION% dans index.html viennent de src/app/brand.ts
    {
      name: 'brand-html',
      transformIndexHtml: (html) =>
        html
          .replaceAll('%BRAND_NAME%', brand.name)
          .replaceAll(
            '%BRAND_DESCRIPTION%',
            `${brand.name} ${brand.description.charAt(0).toLowerCase()}${brand.description.slice(1)}`,
          ),
    },
    react(),
    tailwindcss(),
    VitePWA({
      registerType: 'autoUpdate',
      includeAssets: ['icons/*.svg'],
      manifest: {
        name: brand.name,
        short_name: brand.shortName,
        description: brand.tagline,
        lang: 'fr',
        theme_color: brand.colors.background,
        background_color: brand.colors.background,
        display: 'standalone',
        start_url: '/projet',
        icons: [
          { src: '/icons/icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any' },
          { src: '/icons/icon-maskable.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'maskable' },
        ],
      },
      workbox: {
        navigateFallback: '/index.html',
        navigateFallbackDenylist: [/^\/api/],
      },
    }),
  ],
  resolve: {
    alias: { '@': fileURLToPath(new URL('./src', import.meta.url)) },
  },
  test: {
    environment: 'jsdom',
    globals: true,
    setupFiles: ['./src/test/setup.ts'],
    css: false,
  },
});
